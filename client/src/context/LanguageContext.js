export const LanguageProvider = ({ children }) => {
    const [language, setLanguage] = useState('ru');

    useEffect(() => {
        let savedLanguage = 'ru';
        try { savedLanguage = localStorage.getItem('app-language') === 'en' ? 'en' : 'ru'; } catch {};
        setLanguage(savedLanguage);
        if (typeof document !== 'undefined') {
            document.documentElement.lang = savedLanguage;
        }
    }, []);

    useEffect(() => {
        if (typeof document !== 'undefined') {
            document.documentElement.lang = language;
        }
    }, [language]);

    const changeLanguage = (lang) => {
        setLanguage(lang);
        try { localStorage.setItem('app-language', lang); } catch {};
    };

    const t = (key) => {
        const val = translations[language]?.[key] ?? translations.ru?.[key];
        return (val !== undefined && val !== null) ? val : key;
    };

    return (
        <LanguageContext.Provider value={{ language, changeLanguage, t }}>
            {children}
        </LanguageContext.Provider>
    );
};

export const useLanguage = () => {
    const context = useContext(LanguageContext);
    if (!context) {
        throw new Error('useLanguage must be used within LanguageProvider');
    }
    return context;
};
