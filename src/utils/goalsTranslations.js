// Функция для получения переведенного текста цели
export const getGoalTranslation = (goalId, language, field = 'title') => {
    const translations = goalsTranslations[language] || goalsTranslations.ru;
    const goal = translations[goalId];
    return goal?.[field] || '';
};

// Функция для перевода всего массива целей
export const translateGoals = (goals, language) => {
    if (!Array.isArray(goals) || goals.length === 0) return goals || [];
    
    // Если язык русский, возвращаем оригинальные данные
    if (language === 'ru') {
        return goals;
    }
    
    return goals.map(goal => {
        if (!goal) return goal;
        
        // Пробуем разные варианты ID
        let id = goal.id?.toString();
        let foundId = null;
        
        // Сначала пробуем найти по ID (формат "1"-"75")
        if (id && /^([1-9]|[1-9][0-9]|7[0-5])$/.test(id)) {
            foundId = id;
        } else {
            // Если ID не подходит, пробуем найти по оригинальному русскому title
            const ruTranslations = goalsTranslations.ru;
            const originalTitle = goal.title?.trim();
            
            if (originalTitle) {
                // Точное совпадение
                for (const [key, value] of Object.entries(ruTranslations)) {
                    const ruTitle = value.title?.trim();
                    if (ruTitle === originalTitle) {
                        foundId = key;
                        break;
                    }
                }
                
                // Если не нашли точное совпадение, пробуем частичное
                if (!foundId) {
                    for (const [key, value] of Object.entries(ruTranslations)) {
                        const ruTitle = value.title?.trim();
                        if (ruTitle && (
                            ruTitle === originalTitle ||
                            originalTitle.includes(ruTitle) ||
                            ruTitle.includes(originalTitle) ||
                            originalTitle.replace(/\s+/g, ' ') === ruTitle.replace(/\s+/g, ' ')
                        )) {
                            foundId = key;
                            break;
                        }
                    }
                }
            }
        }
        
        // Если ID не найден, возвращаем оригинал (возможно, это пользовательская цель)
        if (!foundId) {
            return goal;
        }
        
        const translatedTitle = getGoalTranslation(foundId, language, 'title');
        const translatedDescription = getGoalTranslation(foundId, language, 'description');
        
        // Если перевод найден (не пустая строка), используем его, иначе оригинал
        const finalTitle = translatedTitle && translatedTitle.trim() !== '' 
            ? translatedTitle 
            : goal.title;
        
        const finalDescription = translatedDescription && translatedDescription.trim() !== '' 
            ? translatedDescription 
            : (goal.description || '');
        
        return {
            ...goal,
            title: finalTitle,
            description: finalDescription,
        };
    });
};
